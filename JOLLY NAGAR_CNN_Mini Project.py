"""### 5.3 Model 2A: Transfer Learning – VGG16 (Feature Extraction + Fine-Tuning)
We load `VGG16` pre-trained on ImageNet without its top classification head, train the custom head first, and then unfreeze the last convolutional block (`block5`) for fine-tuning at a low learning rate (`1e-5`).
"""

def build_vgg16_model(input_shape=(IMG_SIZE, IMG_SIZE, 3), num_classes=NUM_CLASSES):
    base_model = VGG16(weights="imagenet", include_top=False, input_shape=input_shape)
    base_model.trainable = False  # Freeze base initially

    inputs = layers.Input(shape=input_shape)
    x = base_model(inputs, training=False)
    x = layers.GlobalAveragePooling2D()(x)
    x = layers.Dense(256, activation="relu")(x)
    x = layers.Dropout(0.5)(x)
    outputs = layers.Dense(num_classes, activation="softmax")(x)

    model = models.Model(inputs, outputs, name="VGG16_Transfer")
    model.compile(
        optimizer=optimizers.Adam(learning_rate=1e-3),
        loss="categorical_crossentropy",
        metrics=["accuracy"]
    )
    return model, base_model

vgg16_model, vgg16_base = build_vgg16_model()

