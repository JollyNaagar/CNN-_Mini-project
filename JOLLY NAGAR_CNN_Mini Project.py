"""---
## 7. Model Tuning (Early Stopping & Keras Tuner)

We use **Keras Tuner (`RandomSearch`)** to automatically optimize key CNN hyperparameters:
- Number of convolutional filters (`32` to `256`)
- Dropout rate (`0.2` to `0.5`)
- Dense layer units (`64` to `256`)
- Optimizer choice (`adam` vs `rmsprop`) and Learning Rate (`1e-3`, `5e-4`, `1e-4`)
"""

def build_tunable_cnn(hp):
    model = models.Sequential()
    model.add(layers.Input(shape=(IMG_SIZE, IMG_SIZE, 3)))

    # Tunable Conv Block 1
    hp_filters_1 = hp.Choice("filters_1", values=[32, 64])
    model.add(layers.Conv2D(hp_filters_1, (3, 3), activation="relu", padding="same"))
    model.add(layers.BatchNormalization())
    model.add(layers.MaxPooling2D((2, 2)))

    # Tunable Conv Block 2
    hp_filters_2 = hp.Choice("filters_2", values=[64, 128])
    model.add(layers.Conv2D(hp_filters_2, (3, 3), activation="relu", padding="same"))
    model.add(layers.BatchNormalization())
    model.add(layers.MaxPooling2D((2, 2)))

    # Tunable Conv Block 3
    hp_filters_3 = hp.Choice("filters_3", values=[128, 256])
    model.add(layers.Conv2D(hp_filters_3, (3, 3), activation="relu", padding="same"))
    model.add(layers.BatchNormalization())
    model.add(layers.MaxPooling2D((2, 2)))

    model.add(layers.GlobalAveragePooling2D())

    # Tunable Dense & Dropout
    hp_units = hp.Int("dense_units", min_value=64, max_value=256, step=64)
    model.add(layers.Dense(hp_units, activation="relu"))

    hp_dropout = hp.Float("dropout_rate", min_value=0.2, max_value=0.5, step=0.1)
    model.add(layers.Dropout(hp_dropout))

    model.add(layers.Dense(NUM_CLASSES, activation="softmax"))

    # Tunable Optimizer & Learning Rate
    hp_lr = hp.Choice("learning_rate", values=[1e-3, 5e-4, 1e-4])
    hp_opt = hp.Choice("optimizer", values=["adam", "rmsprop"])

    if hp_opt == "adam":
        opt = optimizers.Adam(learning_rate=hp_lr)
    else:
        opt = optimizers.RMSprop(learning_rate=hp_lr)

    model.compile(
        optimizer=opt,
        loss="categorical_crossentropy",
        metrics=["accuracy"]
    )
    return model

