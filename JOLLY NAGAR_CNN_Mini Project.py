"""### 5.4 Model 2B: Transfer Learning – ResNet50 (Feature Extraction + Fine-Tuning)
We load `ResNet50` pre-trained on ImageNet, train the custom head, and then fine-tune the last 20 layers (keeping BatchNorm layers frozen for stability).
"""

def build_resnet50_model(input_shape=(IMG_SIZE, IMG_SIZE, 3), num_classes=NUM_CLASSES):
    base_model = ResNet50(weights="imagenet", include_top=False, input_shape=input_shape)
    base_model.trainable = False

    inputs = layers.Input(shape=input_shape)
    x = base_model(inputs, training=False)
    x = layers.GlobalAveragePooling2D()(x)
    x = layers.Dense(256, activation="relu")(x)
    x = layers.Dropout(0.5)(x)
    outputs = layers.Dense(num_classes, activation="softmax")(x)

    model = models.Model(inputs, outputs, name="ResNet50_Transfer")
    model.compile(
        optimizer=optimizers.Adam(learning_rate=1e-3),
        loss="categorical_crossentropy",
        metrics=["accuracy"]
    )
    return model, base_model

resnet_model, resnet_base = build_resnet50_model()

cb_res = [callbacks.EarlyStopping(monitor="val_loss", patience=5, restore_best_weights=True)]

